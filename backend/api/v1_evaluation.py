"""
Serves the evaluation suite's results as a versioned API response.

Backed by JSON files generated by eval/run_local_evaluation.py and checked
into the repo (eval/results_v1.json, results_v2.json, results_v2b.json) —
NOT recomputed per-request, since a real run makes real Gemini API calls and
shouldn't re-execute on every page load. Re-run that script after a
meaningful change to a router/retrieval/the knowledge base and commit the
refreshed JSON.

Retrieval hit@k / MRR and groundedness / refusal-rate metrics are a
follow-up (see eval/retrieval_eval.py and the README) — this endpoint
currently serves what's real today: the 3-router comparison from
Milestone 10's harness. `note` says so explicitly rather than silently
omitting those fields.
"""
import json
from pathlib import Path

from fastapi import APIRouter
from pydantic import BaseModel, ConfigDict
from pydantic.alias_generators import to_camel

from core.config import settings

router = APIRouter(prefix="/evaluation", tags=["evaluation (v1)"])

EVAL_DIR = Path(__file__).resolve().parent.parent / "eval"
RETRIEVAL_RESULTS_PATH = EVAL_DIR / "retrieval_results.json"

# router_id -> (display name, results file written by eval/run_local_evaluation.py)
ROUTER_FILES = {
    "rule_based": ("v1 — Rule-based", "results_v1.json"),
    "llm_based": ("v2 — LLM-based (Gemini)", "results_v2.json"),
    "trained_classifier": ("v2b — Trained classifier (Banking77)", "results_v2b.json"),
}


class RouterBenchmarkRow(BaseModel):
    model_config = ConfigDict(alias_generator=to_camel, populate_by_name=True)
    id: str
    name: str
    n_cases: int
    exact_match_rate: float
    hit_rate: float
    avg_precision: float
    avg_latency_ms: float


class RetrievalMetrics(BaseModel):
    model_config = ConfigDict(alias_generator=to_camel, populate_by_name=True)
    n_cases: int
    n_in_kb: int
    n_out_of_kb: int
    hit_at_1: float
    hit_at_3: float
    hit_at_5: float
    mrr_at_5: float
    grounded_retrieval_rate: float
    true_refusal_rate: float
    false_refusal_rate: float


class EvaluationSummaryResponseV1(BaseModel):
    model_config = ConfigDict(alias_generator=to_camel, populate_by_name=True)
    suite_version: str
    commit_hash: str
    total_queries: int | None
    routers: list[RouterBenchmarkRow]
    retrieval: RetrievalMetrics | None
    note: str


def _load_router_results() -> list[RouterBenchmarkRow]:
    rows = []
    for router_id, (display_name, filename) in ROUTER_FILES.items():
        path = EVAL_DIR / filename
        if not path.exists():
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        overall = data["overall"]
        rows.append(RouterBenchmarkRow(
            id=router_id,
            name=display_name,
            n_cases=data["n_cases"],
            exact_match_rate=round(overall["exact_match_rate"] * 100, 1),
            hit_rate=round(overall["hit_rate"] * 100, 1),
            avg_precision=round(overall["avg_precision"] * 100, 1),
            avg_latency_ms=round(overall["avg_latency_ms"], 2),
        ))
    return rows


def _load_retrieval_metrics() -> RetrievalMetrics | None:
    if not RETRIEVAL_RESULTS_PATH.exists():
        return None
    data = json.loads(RETRIEVAL_RESULTS_PATH.read_text(encoding="utf-8"))
    retrieval = data["retrieval"]
    groundedness = data["groundedness"]
    refusal = data["refusal"]
    return RetrievalMetrics(
        n_cases=data["n_cases"],
        n_in_kb=data["n_in_kb"],
        n_out_of_kb=data["n_out_of_kb"],
        hit_at_1=round(retrieval["hit_at_1"] * 100, 1),
        hit_at_3=round(retrieval["hit_at_3"] * 100, 1),
        hit_at_5=round(retrieval["hit_at_5"] * 100, 1),
        mrr_at_5=round(retrieval["mrr_at_5"], 3),
        grounded_retrieval_rate=round(groundedness["grounded_retrieval_rate"] * 100, 1),
        true_refusal_rate=round(refusal["true_refusal_rate"] * 100, 1),
        false_refusal_rate=round(refusal["false_refusal_rate"] * 100, 1),
    )


@router.get("/summary", response_model=EvaluationSummaryResponseV1)
async def evaluation_summary_v1():
    rows = _load_router_results()
    retrieval = _load_retrieval_metrics()
    note = "Router comparison numbers are from a real, committed eval run (backend/eval/run_local_evaluation.py)."
    note += (
        " Retrieval hit@k/MRR/groundedness numbers are real too (backend/eval/retrieval_results.json)."
        if retrieval is not None else
        " Retrieval hit@k/MRR/groundedness haven't been computed yet — run "
        "`python -m scripts.run_retrieval_evaluation` with a real GEMINI_API_KEY and commit the result."
    )
    return EvaluationSummaryResponseV1(
        suite_version="router-comparison-v1" + ("+retrieval-v1" if retrieval else ""),
        commit_hash=settings.git_commit_sha,
        total_queries=rows[0].n_cases if rows else None,
        routers=rows,
        retrieval=retrieval,
        note=note,
    )
